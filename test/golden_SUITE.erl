%% Each NAME.adoc file in the data directory is converted
%% and compared against NAME.html (HTML without header and
%% footer) and NAME.man (manual page) when they exist.
%% Expected files can be regenerated by running the suite
%% with the GOLDEN_UPDATE environment variable set.
-module(golden_SUITE).
-compile(export_all).
-compile(nowarn_export_all).

-import(ct_helper, [doc/1]).

all() ->
	ct_helper:all(?MODULE).

golden(Config) ->
	doc("Convert documents and compare against the expected output."),
	DataDir = config(data_dir, Config),
	Files = filelib:wildcard(filename:join(DataDir, "*.adoc")),
	true = Files =/= [],
	Failed = lists:flatten([golden_file(F, filename:rootname(F)) || F <- Files]),
	case Failed of
		[] -> ok;
		_ -> ct:fail({golden_mismatch, Failed})
	end.

golden_file(File, Base) ->
	AST = asciideck:parse_file(File),
	[
		compare(Base ++ ".html", fun() ->
			asciideck:to_html(AST, #{no_header_footer => true})
		end),
		compare(Base ++ ".man", fun() ->
			asciideck:to_manpage(AST, #{extra1 => "2026-01-01"})
		end)
	].

compare(Expected, Fun) ->
	case file:read_file(Expected) of
		{ok, ExpectedData} ->
			Data = iolist_to_binary(Fun()),
			case {Data, os:getenv("GOLDEN_UPDATE")} of
				{ExpectedData, _} ->
					[];
				{_, false} ->
					ct:pal("~s mismatch:~n~ts", [Expected, Data]),
					[filename:basename(Expected)];
				{_, _} ->
					ok = file:write_file(Expected, Data),
					[]
			end;
		{error, enoent} ->
			[]
	end.

config(Key, Config) ->
	{_, Value} = lists:keyfind(Key, 1, Config),
	Value.
